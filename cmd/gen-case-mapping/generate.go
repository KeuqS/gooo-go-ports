package main

import (
	"fmt"
	"strings"
	"unicode"
)

func generate(pin upstream, tables caseTables) ([]byte, error) {
	if err := validateTables(tables); err != nil {
		return nil, err
	}
	var out strings.Builder
	out.WriteString("// Copyright 2009 The Go Authors. All rights reserved.\n")
	out.WriteString("// Use of this source code is governed by a BSD-style\n// license that can be found in the LICENSE file.\n")
	out.WriteString("// Code generated by go run ./cmd/gen-case-mapping; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Go %s; Unicode %s; source revision %s.\n", strings.TrimPrefix(pin.GoVersion, "go"), pinnedUnicode, pin.GoRevision)
	out.WriteString("// Upstream license: third_party/GO-LICENSE.\n")
	for _, name := range requiredSources {
		fmt.Fprintf(&out, "// SHA256 %s %s\n", name, pin.SourceSHA[name])
	}
	out.WriteString("// To(case, rune): case is a signed int64 Go int on 64-bit Go; rune is int32.\n")
	out.WriteString("// Invalid case takes precedence and returns U+FFFD (65533).\n")
	out.WriteString("// For valid cases, outside-int32 Integer runes return themselves as an\n// explicit extension, without narrowing. Invalid Unicode runes are unchanged.\n")
	out.WriteString("// This is simple one-rune case mapping, not locale-specific mapping,\n// whole-string case conversion, normalization, or SimpleFold.\n")
	out.WriteString("// UpperLower parity is relative to each range's Lo, using arithmetic.\n")
	out.WriteString("// Scalar declarations are shared with space.gooo in this package.\n")
	out.WriteString("package unicode\nnamespace gooo_ports_unicode\n\n")
	fmt.Fprintf(&out, "// All %d pinned CaseRanges appear once in this shared mapping body.\n", len(tables.ranges))
	out.WriteString("activity To(Integer, Integer) -> Integer id \"gooo://go/unicode/To\" computes `")
	out.WriteString("if input0 < 0 || input0 > 2 { return 65533 }\n")
	out.WriteString("if input1 < -2147483648 || input1 > 2147483647 { return input1 }\n")
	out.WriteString("if input1 < 0 || input1 > 1114111 { return input1 }\n")
	writeCases(&out, tables.ranges, 0)
	out.WriteString("`\n\n")
	for _, wrapper := range []struct {
		name      string
		caseIndex int
	}{{"ToUpper", unicode.UpperCase}, {"ToLower", unicode.LowerCase}, {"ToTitle", unicode.TitleCase}} {
		// The pinned ASCII fast path is equivalent to CaseRanges. Calling To
		// keeps that complete mapping in one native Gooo body for composition.
		fmt.Fprintf(&out, "activity %s(Integer) -> Integer id \"gooo://go/unicode/%s\" computes `return To(%d, input)`\n", wrapper.name, wrapper.name, wrapper.caseIndex)
	}
	if out.Len() > 128<<10 {
		return nil, fmt.Errorf("generated Gooo exceeds the pinned composition's 128 KiB source bound")
	}
	return []byte(out.String()), nil
}

func writeCases(out *strings.Builder, ranges []caseRange, depth int) {
	indent := strings.Repeat("\t", depth)
	if len(ranges) == 1 {
		r := ranges[0]
		fmt.Fprintf(out, "%sif input1 < %d || input1 > %d { return input1 }\n", indent, r.lo, r.hi)
		if r.delta[unicode.UpperCase] == unicode.UpperLower {
			// Bounds above make (input1-Lo) nonnegative. Upper/title clear the
			// relative low bit; lower sets it. No overflow or sign ambiguity.
			fmt.Fprintf(out, "%sif input0 == 1 { return input1 + 1 - (input1 - %d) %% 2 }\n", indent, r.lo)
			fmt.Fprintf(out, "%sreturn input1 - (input1 - %d) %% 2", indent, r.lo)
			return
		}
		if r.delta[unicode.UpperCase] == r.delta[unicode.TitleCase] {
			fmt.Fprintf(out, "%sif input0 == 1 { return %s }\n", indent, addDelta(r.delta[unicode.LowerCase]))
			fmt.Fprintf(out, "%sreturn %s", indent, addDelta(r.delta[unicode.UpperCase]))
			return
		}
		fmt.Fprintf(out, "%sif input0 == 0 { return %s }\n", indent, addDelta(r.delta[unicode.UpperCase]))
		fmt.Fprintf(out, "%sif input0 == 1 { return %s }\n", indent, addDelta(r.delta[unicode.LowerCase]))
		fmt.Fprintf(out, "%sreturn %s", indent, addDelta(r.delta[unicode.TitleCase]))
		return
	}
	mid := len(ranges) / 2
	fmt.Fprintf(out, "%sif input1 < %d {\n", indent, ranges[mid].lo)
	writeCases(out, ranges[:mid], depth+1)
	fmt.Fprintf(out, "\n%s} else {\n", indent)
	writeCases(out, ranges[mid:], depth+1)
	fmt.Fprintf(out, "\n%s}", indent)
}

func addDelta(delta int64) string {
	if delta < 0 {
		return fmt.Sprintf("input1 - %d", -delta)
	}
	if delta > 0 {
		return fmt.Sprintf("input1 + %d", delta)
	}
	return "input1"
}
